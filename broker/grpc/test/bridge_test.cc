/**
 * @brief Every protobuf event registered by the core and the modules that
 * carry them has a field in the CentreonEvent oneof, so it can be sent on a
 * serialized gRPC stream, and it comes back with the same BBDO type.
 *
 * The oneof is generated by generate_proto.py from the annotations of the
 * proto files: an event type whose annotation is missing is dropped at
 * sending time ("unable to send unknown event type"), which is how DiffState
 * Broker -> Engine got lost when it shared its message with the global diff.
 */
class grpc_bridge_test : public ::testing::Test {
 protected:
  /* The modules need the singletons of cbd (protocols, events, applier state
   * and its cache, which init() does not create), which other tests unload:
   * they are loaded here and unloaded at the end, as the BAM tests do. The
   * modules themselves are unloaded by the end of the test body, before
   * deinit(). */
  void SetUp() override {
    config::applier::init<config::applier::broker_state>("", 0, "test_broker",
                                                         0);
    config::applier::state::instance().initialize_cache();
  }
  void TearDown() override { config::applier::deinit(); }
};

TEST_F(grpc_bridge_test, every_protobuf_event_has_a_field) {
  /* Events that never leave the cbd that creates them, so they need no field:
   * the local category by design, the requests of the Broker gRPC API
   * (brokerrpc) to unified_sql and BAM, and the poller configuration that
   * broker_state hands to unified_sql. */
  const absl::flat_hash_set<uint32_t> process_internal{
      make_type(io::local, local::de_pb_stop),
      make_type(io::bbdo, bbdo::de_rebuild_graphs),
      make_type(io::bbdo, bbdo::de_remove_graphs),
      make_type(io::bbdo, bbdo::de_remove_poller),
      make_type(io::extcmd, extcmd::de_ba_info),
      make_type(io::neb, neb::de_pb_engine_state)};

  auto logger = log_v2::instance().get(log_v2::CORE);
  config::applier::modules modules(logger);
  modules.load_file("./broker/lib/10-neb.so");
  modules.load_file("./broker/lib/20-bam.so");
  modules.load_file("./broker/lib/20-unified_sql.so");

  size_t checked = 0;
  std::vector<std::string> missing;
  for (const auto& [type, info] :
       io::events::instance().get_events_by_category_name("all")) {
    auto* constructor = info.get_operations().constructor;
    if (!constructor)
      continue;
    std::shared_ptr<io::data> event(constructor());
    if (!std::dynamic_pointer_cast<io::protobuf_base>(event) ||
        process_internal.contains(type))
      continue;
    ++checked;
    auto to_send = com::centreon::broker::grpc::create_event_with_data(event);
    if (!to_send) {
      missing.push_back(fmt::format("{} ({:x})", info.get_name(), type));
      continue;
    }
    auto received =
        std::make_shared<com::centreon::broker::grpc::grpc_event_type>(
            to_send->grpc_event);
    auto back = com::centreon::broker::grpc::protobuf_to_event(received);
    ASSERT_TRUE(back) << info.get_name();
    EXPECT_EQ(back->type(), type) << info.get_name();
  }
  EXPECT_GT(checked, 50u);
  EXPECT_TRUE(missing.empty())
      << "protobuf events without a field in the gRPC oneof: "
      << fmt::format("{}", fmt::join(missing, ", "));
}

/**
 * @brief An event received on a serialized gRPC stream keeps its message in
 * the received CentreonEvent, not in the _obj of io::protobuf: a copy of it
 * (the copy-on-write of the Broker cache clones its entries this way) and an
 * assignment to it must go through obj()/mut_obj(), otherwise they produce an
 * empty message (host_id 0) or leave the received one unchanged.
 */
TEST(grpc_received_protobuf, copy_and_assignment_keep_the_message) {
  auto make_received = [](uint64_t host_id, const std::string& name) {
    auto host = std::make_shared<neb::pb_host>();
    host->mut_obj().set_host_id(host_id);
    host->mut_obj().set_name(name);
    auto to_send = com::centreon::broker::grpc::create_event_with_data(host);
    auto received =
        std::make_shared<com::centreon::broker::grpc::grpc_event_type>(
            to_send->grpc_event);
    return std::static_pointer_cast<neb::pb_host>(
        com::centreon::broker::grpc::protobuf_to_event(received));
  };

  auto received = make_received(50, "host_50");
  ASSERT_TRUE(received);
  ASSERT_EQ(received->obj().host_id(), 50u);

  neb::pb_host copy(*received);
  EXPECT_EQ(copy.obj().host_id(), 50u);
  EXPECT_EQ(copy.obj().name(), "host_50");

  neb::pb_host assigned;
  assigned = *received;
  EXPECT_EQ(assigned.obj().host_id(), 50u);

  auto target = make_received(15, "host_15");
  ASSERT_TRUE(target);
  *target = *received;
  EXPECT_EQ(target->obj().host_id(), 50u);
  EXPECT_EQ(target->obj().name(), "host_50");
}
